#!/usr/bin/env python3
"""Build and publish the GitLab component project the CI/CD Catalog lists. Inert until configured.

The CI/CD Catalog lists components from a project hosted on the GitLab instance itself, with the
components in a top-level `templates/` directory, a README.md at the root, a project description,
and releases created by a CI/CD job that uses the `release` keyword — not by the Releases API — on a
semantic-version tag (https://docs.gitlab.com/ci/components/, "Publish a new release"). This
repository lives on GitHub, so each release is mirrored into such a project, the same way
scripts/publish_actions.py mirrors the GitHub Actions:

    build    --out=<dir> [--project=<group/name>]
        Render the component project into <dir>/<name>/ and stop.
    --check
        Build into a temporary directory and assert the tree is complete, that DISTRIBUTION.json
        names this commit and version, that its .gitlab-ci.yml carries the release job, and that
        `publish` without its two settings publishes nothing. Then publish to local bare repositories.
    publish  --version=X.Y.Z [--dry-run]
        Sync the component project with the build, commit, and push the tag X.Y.Z. The project's own
        pipeline then runs its release job on that tag, which is what creates the Catalog version.

`publish` does nothing at all unless both are set: GITLAB_COMPONENT_PROJECT, the project's full
path, and GITLAB_COMPONENT_TOKEN, a token for that one project that may push to its default branch
and create tags (a project access token with the `write_repository` scope, or, where project access
tokens are not available, a personal access token of an account that is a member of that project
alone). The token is read from the environment by git's credential helper when git asks for it. It
is never put in a URL, an argument, a git config file or a log, and it is only ever offered to an
https remote.

The tag carries no `v`: the Catalog requires a semantic version, and every example in its
documentation is a bare one (`1.0.0`). A released tag is immutable here as in the Actions mirrors.

Stdlib only, like everything else under scripts/.
"""

import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from publish_actions import COMMITTER, SOURCE_REPO, SOURCE_URL, marketplace_version, source_commit  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "contract" / "lib"))
from yaml_mini import load_yaml  # noqa: E402

PROJECT_VARIABLE = "GITLAB_COMPONENT_PROJECT"
TOKEN_VARIABLE = "GITLAB_COMPONENT_TOKEN"
# Where the component project lives. --check points this at local bare repositories.
REMOTE_BASE = os.environ.get("NORU_GITLAB_REMOTE_BASE", "https://gitlab.com/")
PROJECT_RE = re.compile(r"^[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)+$")
PLACEHOLDER_PROJECT = "<group>/<project>"

# One row per component: the name it is included by, and its source in this repository.
COMPONENTS = {
    "noru-ci": "templates/gitlab/noru-ci.yml",
    "noru-review": "templates/gitlab/noru-review.yml",
}
ROOT_FILES = ("LICENSE", "NOTICE")

# The documented release job (https://docs.gitlab.com/ci/components/, "Publish a new release"):
# the `release` keyword in a job that runs for a tag, in an image that has the glab CLI on its PATH
# (https://docs.gitlab.com/ci/yaml/, `release`).
RELEASE_PIPELINE = """\
# Generated by scripts/publish_gitlab_components.py from {source}. Do not edit here; the next
# release overwrites this file.
#
# The CI/CD Catalog creates a version only from a release made by a job that uses the `release`
# keyword, on a semantic-version tag: https://docs.gitlab.com/ci/components/
stages:
  - release

create-release:
  stage: release
  image: registry.gitlab.com/gitlab-org/cli:latest
  rules:
    - if: $CI_COMMIT_TAG
  script: echo "Creating release $CI_COMMIT_TAG"
  release:
    tag_name: $CI_COMMIT_TAG
    description: "Release $CI_COMMIT_TAG of the Noru GRC components, built from {source}. Changes: {changelog}"
"""


def run(args, cwd=None, check=True, env=None, timeout=600):
    return subprocess.run(
        args, cwd=cwd, text=True, capture_output=True, check=check, env=env, timeout=timeout
    )


def component_inputs(text):
    """The spec:inputs of a component template, in order, as (name, default, description)."""
    head, separator, _ = text.partition("\n---\n")
    if not separator:
        return None
    document, _ = load_yaml(head)
    inputs = ((document or {}).get("spec") or {}).get("inputs")
    if not isinstance(inputs, dict):
        return None
    rows = []
    for name, spec in inputs.items():
        spec = spec or {}
        default = spec.get("default", None)
        if isinstance(default, bool):
            default = "true" if default else "false"
        rows.append((name, default, str(spec.get("description") or "").strip()))
    return rows


def readme(project, version):
    lines = [
        "# Noru GRC CI/CD components",
        "",
        "Re-check a committed Noru compliance manifest on each merge request and fail when it drifts",
        "from the code, offline by default; and route a merge request's changes to the checks they",
        "implicate. The GitLab counterparts of the noru-ci and noru-review GitHub Actions.",
        "",
        "## Usage",
        "",
        "```yaml",
        "include:",
        f"  - component: $CI_SERVER_FQDN/{project}/noru-ci@{version}",
        "    inputs:",
        "      piece: ai-inventory",
        f"  - component: $CI_SERVER_FQDN/{project}/noru-review@{version}",
        "```",
        "",
        f"`@{version.split('.')[0]}` follows the newest {version.split('.')[0]}.x release and `@~latest`"
        " the newest of all; a",
        "full version is the only form that never changes underneath you.",
        "",
        "Components can be included only from the GitLab instance that hosts them. On GitLab",
        "Self-Managed, where CI/CD components are generally available from GitLab 17.0, mirror this",
        "project and set the mirror as a catalog project, or include the same templates with",
        "`include: remote` from a",
        f"release tag of [{SOURCE_REPO}]({SOURCE_URL}/tree/v{version}/templates/gitlab).",
        "",
        "Full documentation, including the merge request note and its token, the reports each job",
        f"writes, and what is checked: [docs/ci-mode.md]({SOURCE_URL}/blob/v{version}/docs/ci-mode.md#gitlab-ci).",
        "",
    ]
    for name, source in COMPONENTS.items():
        rows = component_inputs((ROOT / source).read_text(encoding="utf-8")) or []
        lines += [f"## `{name}` inputs", "", "| Input | Default | Description |", "|---|---|---|"]
        for input_name, default, description in rows:
            shown = "*(required)*" if default is None else f"`{default}`" if default != "" else "*(empty)*"
            lines.append(f"| `{input_name}` | {shown} | {description.replace('|', '/')} |")
        lines.append("")
    lines += [
        "> **Distribution project.** This project is generated from",
        f"> [{SOURCE_REPO}]({SOURCE_URL}) by `scripts/publish_gitlab_components.py` on every release:",
        "> do not edit it here, changes land upstream and the next release overwrites this tree.",
        f"> Issues and private vulnerability reports: {SOURCE_URL}/security/advisories/new",
        "",
    ]
    return "\n".join(lines)


def build(out_dir, version=None, commit=None, project=None):
    version = version or marketplace_version()
    commit = commit or source_commit()
    project = project or PLACEHOLDER_PROJECT
    name = project.rsplit("/", 1)[-1].strip("<>") or "project"
    tree = pathlib.Path(out_dir) / name
    if tree.exists():
        shutil.rmtree(tree)
    (tree / "templates").mkdir(parents=True)
    for component, source in COMPONENTS.items():
        shutil.copy2(ROOT / source, tree / "templates" / f"{component}.yml")
    for root_file in ROOT_FILES:
        if (ROOT / root_file).is_file():
            shutil.copy2(ROOT / root_file, tree / root_file)
    (tree / "README.md").write_text(readme(project, version), encoding="utf-8")
    (tree / ".gitlab-ci.yml").write_text(
        RELEASE_PIPELINE.format(
            source=f"{SOURCE_REPO}@{commit}",
            changelog=f"{SOURCE_URL}/blob/v{version}/CHANGELOG.md",
        ),
        encoding="utf-8",
    )
    provenance = {
        "component_project": project,
        "components": {component: f"templates/{component}.yml" for component in COMPONENTS},
        "version": version,
        "source_repository": SOURCE_REPO,
        "source_paths": dict(COMPONENTS),
        "source_commit": commit,
        "generated_by": "scripts/publish_gitlab_components.py",
        "note": "Generated on release. Edit upstream, never here.",
    }
    (tree / "DISTRIBUTION.json").write_text(json.dumps(provenance, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return tree


# --- publish -------------------------------------------------------------------------------------


def log(message):
    print(message, flush=True)


def configured(env):
    """(project, token present) or (None, reason). Nothing is published unless both are set."""
    project = (env.get(PROJECT_VARIABLE) or "").strip()
    has_token = bool(env.get(TOKEN_VARIABLE))
    if not project or not has_token:
        missing = [name for name, ok in ((PROJECT_VARIABLE, project), (TOKEN_VARIABLE, has_token)) if not ok]
        return None, f"{' and '.join(missing)} not set, so there is no GitLab component project to publish to"
    if not PROJECT_RE.match(project):
        return None, f"{PROJECT_VARIABLE} must be a full project path such as group/name, got {project!r}"
    return project, None


def git_env(url):
    """The environment git runs in, and the arguments that let it authenticate.

    For an https remote, a credential helper prints the token from the environment when git asks,
    so the value is never an argument, never in a URL and never in a config file. The empty
    `credential.helper=` first clears any helper the runner has configured, so no store or cache
    helper is ever handed the token to keep.
    """
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0"}
    if url.startswith("https://"):
        helper = (
            '!f() { test "$1" = get || return 0; echo username=noru-release; '
            f'echo "password=${TOKEN_VARIABLE}"; }}; f'
        )
        return env, ["-c", "credential.helper=", "-c", f"credential.helper={helper}"]
    env.pop(TOKEN_VARIABLE, None)
    return env, []


def redact(text):
    token = os.environ.get(TOKEN_VARIABLE)
    text = str(text)
    return text.replace(token, "<redacted>") if token else text


def publish(version, dry_run, env=os.environ):
    project, reason = configured(env)
    if project is None:
        log(f"skipped: {reason}. Nothing was published.")
        return 0
    expected = marketplace_version()
    if version != expected:
        raise SystemExit(
            f"error: --version={version} but the checked-out tree is {expected}. Publish from the "
            f"v{version} tag so the component project carries exactly the released templates."
        )
    url = f"{REMOTE_BASE.rstrip('/')}/{project}.git"
    if not (url.startswith("https://") or url.startswith("file://")):
        raise SystemExit("error: the component project is reached over https only; the token is never sent over plain http")
    environment, auth = git_env(url)
    git = ["git", *auth, "-c", f"user.name={COMMITTER[0]}", "-c", f"user.email={COMMITTER[1]}"]
    commit = source_commit()
    tag = version
    log(f"\n== GitLab components -> {project} @ {tag}")
    with tempfile.TemporaryDirectory(prefix="noru-gitlab-components-") as tmp:
        tree = build(pathlib.Path(tmp) / "build", version, commit, project)
        work = pathlib.Path(tmp) / "work"
        try:
            run([*git, "clone", "--quiet", url, str(work)], env=environment)
        except subprocess.CalledProcessError as exc:
            raise SystemExit(
                f"error: cannot clone {url}: {redact(exc.stderr.strip())}\n"
                "Create the project first (once), set its description, and set it as a catalog "
                "project. CONTRIBUTING.md, 'GitLab CI/CD Catalog', has the steps."
            ) from None
        has_head = run(["git", "rev-parse", "--verify", "HEAD"], cwd=work, check=False).returncode == 0
        branch = run(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=work).stdout.strip() if has_head else "main"
        if not has_head:
            run(["git", "checkout", "-q", "-b", branch], cwd=work)
        for entry in work.iterdir():
            if entry.name != ".git":
                shutil.rmtree(entry) if entry.is_dir() else entry.unlink()
        for entry in tree.iterdir():
            target = work / entry.name
            shutil.copytree(entry, target) if entry.is_dir() else shutil.copy2(entry, target)
        run(["git", "add", "-A"], cwd=work)
        pushes = []
        if run(["git", "status", "--porcelain"], cwd=work).stdout.strip():
            message = f"chore: release {version}\n\nGenerated from {SOURCE_REPO}@{commit} (v{version}) by scripts/publish_gitlab_components.py.\n"
            run([*git, "commit", "-q", "-m", message], cwd=work, env=environment)
            pushes.append(["push", "origin", f"HEAD:refs/heads/{branch}"])
            log(f"   commit: tree changed, committed release {version}")
        else:
            log("   commit: tree already matches, nothing to commit")

        head_tree = run(["git", "rev-parse", "HEAD^{tree}"], cwd=work).stdout.strip()
        if run(["git", "tag", "-l", tag], cwd=work).stdout.strip():
            tagged_tree = run(["git", "rev-parse", f"{tag}^{{tree}}"], cwd=work).stdout.strip()
            if tagged_tree != head_tree:
                raise SystemExit(
                    f"error: {project} already has {tag} pointing at a different tree. A released tag is "
                    "immutable; bump the version instead of republishing different content under it."
                )
            log(f"   tag: {tag} already exists and matches")
        else:
            run([*git, "tag", "-a", tag, "-m", f"Noru GRC components {tag} (from {SOURCE_REPO}@{commit})"], cwd=work, env=environment)
            pushes.append(["push", "origin", f"refs/tags/{tag}"])
            log(f"   tag: created {tag}; the project's release job creates the Catalog version from it")

        for command in pushes:
            if dry_run:
                log(f"   dry-run: git {' '.join(command)}")
                continue
            completed = run([*git, *command], cwd=work, env=environment, check=False)
            if completed.returncode != 0:
                raise SystemExit(f"error: git {' '.join(command)} failed: {redact(completed.stderr.strip())}")
            log(f"   pushed: {command[-1]}")
    log("\ndone" + (" (dry run, nothing pushed)" if dry_run else ""))
    return 0


# --- check ---------------------------------------------------------------------------------------


class Results:
    def __init__(self):
        self.rows = []

    def check(self, name, ok, detail=""):
        self.rows.append({"test": name, "ok": bool(ok), "detail": str(detail)[:1000]})

    def finish(self, output_json, quiet):
        ok = all(row["ok"] for row in self.rows)
        if output_json:
            print(json.dumps({"ok": ok, "total": len(self.rows), "results": self.rows}))
        elif not quiet:
            for row in self.rows:
                print(f"  {'ok' if row['ok'] else 'FAIL':4}  {row['test']}")
                if not row["ok"] and row["detail"]:
                    print(f"        {row['detail'][:300]}")
            print(f"\n{'OK' if ok else 'FAILED'}: {len(self.rows)} GitLab component distribution checks.")
        elif not ok:
            for row in self.rows:
                if not row["ok"]:
                    print(f"  FAIL  {row['test']}: {row['detail'][:300]}")
        return 0 if ok else 1


def check_tree(results, tmp):
    version = marketplace_version()
    commit = source_commit()
    project = "example-group/noru-grc-components"
    tree = build(tmp / "build", version, commit, project)
    expected = [".gitlab-ci.yml", "README.md", "LICENSE", "DISTRIBUTION.json"] + [
        f"templates/{name}.yml" for name in COMPONENTS
    ]
    results.check(
        "component project holds templates/<component>.yml, README.md, LICENSE, DISTRIBUTION.json and .gitlab-ci.yml",
        all((tree / name).is_file() for name in expected),
        sorted(str(p.relative_to(tree)) for p in tree.rglob("*") if p.is_file()),
    )
    for name, source in COMPONENTS.items():
        text = (ROOT / source).read_text(encoding="utf-8")
        results.check(
            f"[{name}] templates/{name}.yml is the in-tree template, byte for byte",
            (tree / "templates" / f"{name}.yml").read_bytes() == (ROOT / source).read_bytes(),
        )
        rows = component_inputs(text)
        results.check(f"[{name}] has a spec:inputs header followed by ---", bool(rows), source)
        defaults = {row[0]: row[1] for row in rows or []}
        results.check(
            f"[{name}] runs the toolkit at this release: toolkit-version defaults to v{version}",
            defaults.get("toolkit-version") == f"v{version}",
            defaults.get("toolkit-version"),
        )
        results.check(
            f"[{name}] NORU_API_KEY and the note token are never inputs",
            not any(re.search(r"(?i)api[-_]?key|token$", row[0]) for row in rows or []),
            [row[0] for row in rows or []],
        )
        readme_text = (tree / "README.md").read_text(encoding="utf-8")
        results.check(
            f"[{name}] README shows `include: component:` at this version and documents every input",
            f"component: $CI_SERVER_FQDN/{project}/{name}@{version}" in readme_text
            and all(f"| `{row[0]}` |" in readme_text for row in rows or []),
        )
    provenance = json.loads((tree / "DISTRIBUTION.json").read_text(encoding="utf-8"))
    results.check(
        "DISTRIBUTION.json names this source commit, this version and the source templates",
        provenance.get("source_commit") == commit
        and provenance.get("version") == version
        and provenance.get("source_repository") == SOURCE_REPO
        and provenance.get("source_paths") == COMPONENTS,
        provenance,
    )
    pipeline, _ = load_yaml((tree / ".gitlab-ci.yml").read_text(encoding="utf-8"))
    job = (pipeline or {}).get("create-release") or {}
    results.check(
        ".gitlab-ci.yml has the release job the Catalog requires: the release keyword, on a tag",
        (job.get("release") or {}).get("tag_name") == "$CI_COMMIT_TAG"
        and {"if": "$CI_COMMIT_TAG"} in (job.get("rules") or [])
        and job.get("stage") in (pipeline or {}).get("stages", []),
        job,
    )
    readme_text = (tree / "README.md").read_text(encoding="utf-8")
    results.check(
        "README states the self-managed minimum (GitLab 17.0) and the distribution banner",
        "GitLab 17.0" in readme_text and "> **Distribution project.**" in readme_text,
    )


def publish_cli(env, *args):
    return run(
        [sys.executable, str(pathlib.Path(__file__).resolve()), "publish", f"--version={marketplace_version()}", *args],
        env=env, check=False,
    )


def check_publish(results, tmp):
    version = marketplace_version()
    project = "example-group/noru-grc-components"
    remotes = tmp / "remotes"
    bare = remotes / f"{project}.git"
    bare.parent.mkdir(parents=True, exist_ok=True)
    run(["git", "init", "-q", "--bare", "-b", "main", str(bare)])
    base = {k: v for k, v in os.environ.items() if k not in (PROJECT_VARIABLE, TOKEN_VARIABLE)}
    base["NORU_GITLAB_REMOTE_BASE"] = remotes.as_uri()
    # Assembled at runtime and shaped like nothing check_repo.py looks for: it is never a real token.
    fake = "fixture-component-" + "0123456789" * 2

    def refs():
        return run(["git", "for-each-ref", "--format=%(refname)"], cwd=bare, check=False).stdout.split()

    for label, extra in (
        ("neither setting", {}),
        (f"only {PROJECT_VARIABLE}", {PROJECT_VARIABLE: project}),
        (f"only {TOKEN_VARIABLE}", {TOKEN_VARIABLE: fake}),
    ):
        completed = publish_cli({**base, **extra})
        results.check(
            f"[gate] {label}: publish is skipped, exits 0, and the project receives nothing",
            completed.returncode == 0 and "skipped" in completed.stdout and not refs(),
            completed.stdout + completed.stderr,
        )

    configured_env = {**base, PROJECT_VARIABLE: project, TOKEN_VARIABLE: fake}
    first = publish_cli(configured_env)
    results.check(
        "[publish] first run commits and pushes the bare semantic-version tag (no v)",
        first.returncode == 0 and f"refs/tags/{version}" in refs() and f"refs/tags/v{version}" not in refs(),
        first.stdout + first.stderr,
    )
    shown = run(["git", "show", f"{version}:DISTRIBUTION.json"], cwd=bare, check=False).stdout
    results.check(
        "[publish] the pushed DISTRIBUTION.json names this source commit",
        json.loads(shown or "{}").get("source_commit") == source_commit(),
        shown[:200],
    )
    second = publish_cli(configured_env)
    results.check(
        "[publish] a second run of the same version is a no-op",
        second.returncode == 0 and "nothing to commit" in second.stdout and "already exists and matches" in second.stdout,
        second.stdout + second.stderr,
    )
    results.check(
        "[publish] the token never appears in any output",
        all(fake not in out for out in (first.stdout, first.stderr, second.stdout, second.stderr)),
    )
    clone = tmp / "tamper"
    run(["git", "clone", "-q", str(bare), str(clone)])
    (clone / "TAMPERED").write_text("x\n", encoding="utf-8")
    git = ["git", "-c", "user.name=t", "-c", "user.email=t@example.com"]
    run(["git", "add", "-A"], cwd=clone)
    run([*git, "commit", "-q", "-m", "tamper"], cwd=clone)
    run([*git, "tag", "-f", version], cwd=clone)
    run(["git", "push", "-q", "--force", "origin", f"refs/tags/{version}"], cwd=clone)
    third = publish_cli(configured_env)
    results.check(
        "[publish] a released tag that points elsewhere is a hard failure, never overwritten",
        third.returncode != 0 and "immutable" in third.stderr,
        third.stdout + third.stderr,
    )
    plain = publish_cli({**configured_env, "NORU_GITLAB_REMOTE_BASE": "http://gitlab.example.invalid/"})
    results.check(
        "[publish] a plain-http remote is refused before git runs, so the token is never offered to it",
        plain.returncode != 0 and "https only" in plain.stderr and "cannot clone" not in plain.stderr,
        plain.stdout + plain.stderr,
    )
    env, auth = git_env("https://gitlab.example.invalid/example-group/project.git")
    results.check(
        "[publish] the https credential helper reads the token from the environment, not from its own text",
        auth and fake not in " ".join(auth) and f"${TOKEN_VARIABLE}" in " ".join(auth) and auth[1] == "credential.helper=",
        auth,
    )
    # And that git, asking it, gets the token: the helper is the only way the value reaches git.
    filled = subprocess.run(
        ["git", *auth, "credential", "fill"], input="protocol=https\nhost=gitlab.example.invalid\n\n",
        text=True, capture_output=True, check=False, timeout=60,
        env={**env, TOKEN_VARIABLE: fake},
    )
    results.check(
        "[publish] git's credential fill gets the token from the helper, at the point of use",
        filled.returncode == 0 and f"password={fake}" in filled.stdout,
        redact(filled.stderr).replace(fake, "<redacted>"),
    )


def check(output_json, quiet):
    results = Results()
    with tempfile.TemporaryDirectory(prefix="noru-gitlab-components-") as tmp:
        tmp = pathlib.Path(tmp)
        check_tree(results, tmp)
        check_publish(results, tmp)
    return results.finish(output_json, quiet)


# --- cli -----------------------------------------------------------------------------------------

USAGE = """usage:
  publish_gitlab_components.py build --out=<dir> [--project=<group/name>]
  publish_gitlab_components.py --check [--output=json] [--quiet]
  publish_gitlab_components.py publish --version=X.Y.Z [--dry-run]
publish reads GITLAB_COMPONENT_PROJECT and GITLAB_COMPONENT_TOKEN, and does nothing without both."""


def main(argv):
    command = None
    opts = {"out": None, "project": None, "version": None, "dry_run": False, "json": False, "quiet": False, "check": False}
    for arg in argv:
        if arg in ("build", "publish") and command is None:
            command = arg
        elif arg == "--check":
            opts["check"] = True
        elif arg.startswith("--out="):
            opts["out"] = pathlib.Path(arg.split("=", 1)[1]).resolve()
        elif arg.startswith("--project="):
            opts["project"] = arg.split("=", 1)[1]
        elif arg.startswith("--version="):
            opts["version"] = arg.split("=", 1)[1].lstrip("v")
        elif arg == "--dry-run":
            opts["dry_run"] = True
        elif arg == "--output=json":
            opts["json"] = True
        elif arg == "--output=text":
            opts["json"] = False
        elif arg == "--quiet":
            opts["quiet"] = True
        elif arg in ("-h", "--help"):
            print(USAGE)
            return 0
        else:
            sys.stderr.write(f"error: unknown option '{arg}'\n{USAGE}\n")
            return 2

    if opts["check"]:
        return check(opts["json"], opts["quiet"])
    if command == "build":
        if not opts["out"]:
            sys.stderr.write("error: build needs --out=<dir>\n")
            return 2
        if opts["project"] and not PROJECT_RE.match(opts["project"]):
            sys.stderr.write("error: --project must be a full project path such as group/name\n")
            return 2
        print(build(opts["out"], project=opts["project"]))
        return 0
    if command == "publish":
        if not opts["version"] or not re.fullmatch(r"\d+\.\d+\.\d+", opts["version"]):
            sys.stderr.write("error: publish needs --version=X.Y.Z\n")
            return 2
        return publish(opts["version"], opts["dry_run"])
    sys.stderr.write(USAGE + "\n")
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
