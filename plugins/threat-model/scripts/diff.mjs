#!/usr/bin/env node
// :diff for the threat-model piece — contract requirement 5.
//
// Reads two local files and writes nothing to Noru:
//   .noru/.cache/threat-model.parsed.json  the validated manifest (validate_manifest.py)
//   .noru/.cache/noru-state.json           the risks this piece already filed, written by the skill
//                                          from getOrganizationRisks; and, when the skill could read
//                                          them, each risk's linked controls from
//                                          getRiskControlMappings (`risk_controls`)
//
// One risk per threat on each component or dataflow:
//
//   absent     createRisk, with the externalId `threat-model:<slug>:<key>`. No upsert on externalId
//              is documented, so this is a probe: the snapshot is read first. Noru refuses a second
//              risk with the same externalId, so a probe that missed one fails loudly rather than
//              filing a duplicate.
//   present    updateRisk with every field this piece writes, when one of them differs.
//   gone       a risk this repository filed that the model no longer names is resolved, with the
//              same updateRisk. Taken out of the model is not the same as treated; the reason says so.
//
// Controls: a new risk is linked to its controls in the same push (linkRiskToControl carries
// `depends_on` and takes the id the createRisk call returns). An existing risk's links are compared
// only when the snapshot carries them; without them the link is not planned, and the plan says why,
// because linkRiskToControl refuses a link that already exists. Links are never removed.
//
// Usage: node diff.mjs [--repo=<path>] [--output=json|text] [--quiet]
// Exit codes: 0 plan written, 1 missing/unusable input, 2 usage error.

import { existsSync, readFileSync, realpathSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import {
  parseCommonArgs,
  planPathFor,
  renderPlanText,
  sha256OfFile,
  summarize,
  writePlan,
} from "./lib/plan.mjs";

const PIECE = "threat-model";
const MARKER = "noru-grc-engineering:threat-model:";
const USAGE = "usage: diff.mjs [--repo=<path>] [--output=json|text] [--quiet]\n";

// What makes a re-run a no-op: every field this piece writes.
const COMPARED_FIELDS = [
  "title", "status", "category", "likelihood", "impact", "description", "mitigationStrategy",
];

export function externalIdFor(slug, key) {
  return `threat-model:${slug}:${key}`;
}

function loadJson(path, label) {
  if (!existsSync(path)) return { error: `${label} not found at ${path}` };
  try {
    return { value: JSON.parse(readFileSync(path, "utf8")) };
  } catch (error) {
    return { error: `${label} at ${path} is not readable JSON (${error.message})` };
  }
}

/** The risk body. The first line carries the marker the probe finds it by. */
export function riskDescription(risk, manifest, externalId) {
  const src = manifest.source;
  const otm = risk.otm ?? {};
  const lines = [
    `${MARKER}${externalId}`,
    "",
    `Threat: ${risk.threat.name} (${risk.threat.id})`,
    `On ${risk.target.kind}: ${risk.target.name} (${risk.target.id})`,
    `Model: ${risk.model}`,
    `Model state: ${otm.state ?? "none"}; likelihood ${otm.likelihood ?? "-"}/100, impact ${otm.impact ?? "-"}/100`,
    "",
    "Cited at:",
    ...(risk.refs ?? []).map((r) => `  - ${r}`),
    "",
    `Decided by: ${risk.interpretation.owner} on ${risk.interpretation.decided_at}`,
    `Stands until: ${risk.interpretation.expires_at}`,
    `Reasoning: ${risk.interpretation.rationale}`,
    "",
    `Source: ${src.slug} @ ${src.commit_sha} (${src.branch})`,
    `Generated by: ${src.generated_by}`,
  ];
  return lines.join("\n");
}

export function mitigationStrategy(risk) {
  const rows = risk.mitigations ?? [];
  if (rows.length === 0) return "No mitigation is recorded in the threat model.";
  return rows.map((m) => `${m.name} (${m.state ?? "state not recorded"})`).join("; ");
}

function provenanceOf(manifest) {
  const src = manifest.source;
  return { slug: src.slug, commit_sha: src.commit_sha, branch: src.branch };
}

/** The risk this piece filed under `externalId`, by the field or by the marker in its description. */
function filed(rows, externalId) {
  return rows.find(
    (r) =>
      r.externalId === externalId ||
      (typeof r.description === "string" && r.description.startsWith(`${MARKER}${externalId}\n`))
  );
}

function externalIdOf(row) {
  if (typeof row.externalId === "string" && row.externalId !== "") return row.externalId;
  const first = typeof row.description === "string" ? row.description.split("\n", 1)[0] : "";
  return first.startsWith(MARKER) ? first.slice(MARKER.length) : null;
}

/** The state snapshot is untrusted tool output. It is compared against, never obeyed. */
export function buildOperations(manifest, state) {
  const rows = (state.risks ?? []).filter((r) => r && typeof r === "object");
  const links = state.risk_controls ?? null;
  const slug = manifest.source.slug;
  const provenance = provenanceOf(manifest);
  const operations = [];
  const claimed = new Set();

  for (const risk of manifest.risks ?? []) {
    const externalId = externalIdFor(slug, risk.key);
    claimed.add(externalId);
    const desired = {
      title: risk.title,
      status: risk.status,
      category: risk.category,
      likelihood: risk.likelihood,
      impact: risk.impact,
      description: riskDescription(risk, manifest, externalId),
      mitigationStrategy: mitigationStrategy(risk),
    };
    const tags = [PIECE, `${risk.target.kind}:${risk.target.id}`, `threat:${risk.threat.id}`];
    const existing = filed(rows, externalId);
    let createIndex = null;
    if (!existing) {
      createIndex = operations.length;
      operations.push({
        operation: "createRisk",
        transport: "mcp",
        scope: "write:risks",
        subject: `${risk.title}`,
        effect: "create",
        reason: "no risk carries this externalId or marker yet",
        idempotency: { kind: "client_probe", key: ["externalId"] },
        arguments: { ...desired, externalId, tags },
      });
    } else {
      const changed = COMPARED_FIELDS.filter((f) => (existing[f] ?? null) !== desired[f]);
      operations.push({
        operation: "updateRisk",
        transport: "mcp",
        scope: "write:risks",
        subject: `${risk.title}`,
        effect: changed.length > 0 ? "update" : "skip",
        reason:
          changed.length > 0
            ? `risk ${existing.id} already exists; ${changed.join(", ")} would change`
            : `risk ${existing.id} already says exactly this`,
        idempotency: { kind: "client_probe", key: ["riskId"] },
        arguments: { riskId: existing.id, ...desired, externalId, tags },
      });
    }
    for (const controlId of [...(risk.controls ?? [])].sort()) {
      if (createIndex !== null) {
        operations.push({
          operation: "linkRiskToControl",
          transport: "mcp",
          scope: "write:risks",
          subject: `link ${risk.title} to ${controlId}`,
          effect: "create",
          reason: "the risk does not exist yet",
          idempotency: { kind: "client_probe", key: ["riskId", "controlId"] },
          depends_on: {
            operation_index: createIndex,
            field: "riskId",
            note: "substitute the risk id returned by the createRisk call above",
          },
          arguments: { riskId: null, controlId },
        });
        continue;
      }
      const known = links && Array.isArray(links[existing.id]) ? links[existing.id] : null;
      const linked = known !== null && known.includes(controlId);
      operations.push({
        operation: "linkRiskToControl",
        transport: "mcp",
        scope: "write:risks",
        subject: `link ${risk.title} to ${controlId}`,
        effect: known === null || linked ? "skip" : "create",
        reason:
          known === null
            ? `risk ${existing.id} exists and its links are not in the snapshot; run :diff interactively (it reads getRiskControlMappings) to link a control added since`
            : linked
              ? `risk ${existing.id} is already linked to ${controlId}`
              : `risk ${existing.id} is not linked to ${controlId} yet`,
        idempotency: { kind: "client_probe", key: ["riskId", "controlId"] },
        arguments: { riskId: existing.id, controlId },
      });
    }
  }

  // The resolving half: this repository's risks the model no longer names.
  const mine = `threat-model:${slug}:`;
  const orphans = rows
    .map((row) => ({ row, externalId: externalIdOf(row) }))
    .filter(({ externalId }) => externalId !== null && externalId.startsWith(mine))
    .filter(({ externalId }) => !claimed.has(externalId))
    .sort((a, b) => (a.externalId < b.externalId ? -1 : a.externalId > b.externalId ? 1 : 0));
  for (const { row, externalId } of orphans) {
    const resolved = row.status === "resolved";
    operations.push({
      operation: "updateRisk",
      transport: "mcp",
      scope: "write:risks",
      subject: `resolve: ${row.title ?? externalId}`,
      effect: resolved ? "skip" : "update",
      reason: resolved
        ? `${externalId} is already resolved in Noru`
        : `${externalId} is ${row.status ?? "open"} in Noru and the threat model no longer names it at ${provenance.commit_sha}; taken out of the model is not the same as treated`,
      idempotency: { kind: "client_probe", key: ["riskId"] },
      arguments: {
        riskId: row.id,
        status: "resolved",
        notes: `Resolved by ${manifest.source.generated_by}: the threat model at ${provenance.slug} @ ${provenance.commit_sha} no longer names this threat.`,
      },
    });
  }
  return operations;
}

function main(argv) {
  const opts = parseCommonArgs(argv);
  if (opts.help) {
    process.stdout.write(USAGE);
    return 0;
  }
  if (opts.rest.length > 0) {
    process.stderr.write(`error: unexpected argument '${opts.rest[0]}'\n${USAGE}`);
    return 2;
  }
  const manifestPath = join(opts.repo, ".noru", "threat-model.yml");
  const parsedPath = join(opts.repo, ".noru", ".cache", "threat-model.parsed.json");
  const statePath = join(opts.repo, ".noru", ".cache", "noru-state.json");
  if (!existsSync(manifestPath)) {
    process.stderr.write(`error: no manifest at ${manifestPath} — run the piece's :scan command first\n`);
    return 1;
  }
  const parsed = loadJson(parsedPath, "validated manifest");
  if (parsed.error) {
    process.stderr.write(
      `error: ${parsed.error}\n` +
        "hint: python3 <plugin>/scripts/validate_manifest.py .noru/threat-model.yml " +
        "--emit-parsed=.noru/.cache/threat-model.parsed.json\n"
    );
    return 1;
  }
  const state = loadJson(statePath, "Noru state snapshot");
  if (state.error) {
    process.stderr.write(
      `error: ${state.error}\n` +
        "hint: the skill writes this from getOrganizationRisks before running :diff. Without it the " +
        "plan cannot tell a new risk from one already filed\n"
    );
    return 1;
  }
  const manifest = parsed.value;
  const operations = buildOperations(manifest, state.value);
  const plan = writePlan(planPathFor(opts.repo, PIECE), {
    repo: opts.repo,
    state: state.value,
    created_at: state.value.fetched_at ?? manifest.source.commit_sha,
    piece: PIECE,
    manifest: ".noru/threat-model.yml",
    manifest_sha256: sha256OfFile(manifestPath),
    provenance: provenanceOf(manifest),
    operations,
    summary: summarize(operations),
  });
  if (opts.json) {
    process.stdout.write(`${JSON.stringify(plan, null, opts.quiet ? 0 : 2)}\n`);
  } else if (!opts.quiet) {
    process.stdout.write(`${renderPlanText(plan)}\n`);
  }
  return 0;
}

// Reduce both sides to one form before comparing: `import.meta.url` is the realpath and is
// percent-encoded, while `process.argv[1]` is the path as it was typed — and /tmp and /var are
// symlinks on macOS, so the two differ routinely. A raw comparison is then false and the script
// exits 0 having done nothing. realpathSync throws when argv[1] is not a path at all (`node -e`,
// or an import), which is not a direct invocation either.
function invokedAsScript() {
  try {
    return import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href;
  } catch {
    return false;
  }
}

if (invokedAsScript()) {
  process.exit(main(process.argv.slice(2)));
}
